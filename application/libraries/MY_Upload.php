<?php
defined('BASEPATH') OR exit('No direct script access allowed');

class MY_Upload extends CI_Upload
{
	protected array $uploadConfig;

	/**
	 * 저장소가 S3이면 업로드한 파일의 s3:// 경로 (data()의 full_path로 돌려줌)
	 */
	protected $storedUri = null;

	/**
	 * 업로드 후 저장소가 S3이면 S3로 올리고 로컬 파일은 지운다
	 */
	public function do_upload($field = 'userfile')
	{
		$this->storedUri = null;
		if (!parent::do_upload($field)) return FALSE;

		$this->_CI->load->library('storage');
		if (!$this->_CI->storage->isS3()) return TRUE;

		$localPath = $this->upload_path . $this->file_name;
		$key = $this->_CI->storage->keyFromUri($localPath);
		$stored = $this->_CI->storage->putFile($key, $localPath);
		@unlink($localPath);

		if (!$stored) {
			$this->set_error('upload_destination_error', 'error');
			return FALSE;
		}

		$this->storedUri = $this->_CI->storage->uri($key);
		return TRUE;
	}

	function data($index = NULL)
	{
		$data = parent::data();
		if ($this->storedUri) {
			$data['full_path'] = $this->storedUri;
			$data['file_path'] = dirname($this->storedUri) . '/';
		}
		// 전체 주소가 아닌 저장소 키로 (주소는 Model_File 이 읽을 때 get_file_url 로 만든다)
		$data['file_link'] = get_file_key_from_path($data['full_path']);

		if (!empty($index)) return $data[$index] ?? NULL;
		return $data;
	}

	public function initialize(array $config = array(), $reset = TRUE)
	{
		$this->uploadConfig = $config;

		return parent::initialize($config, $reset); // TODO: Change the autogenerated stub
	}

	public function set_error($msg, $log_level = 'error')
	{
		if(in_array($msg, ['upload_file_exceeds_limit','upload_file_exceeds_form_limit','upload_invalid_filesize','upload_invalid_filetype'])) {
			$this->_CI->lang->load('upload', config_item('language'));

			$line = $replace = '';
			switch ($msg)
			{
				case 'upload_file_exceeds_limit' :
					// 서버에 설정된 업로드 용량을 초과하였습니다.
					$line = 'allowed_maximum_upload_limit';
					$replace = get_file_size(UPLOAD_MAX_FILESIZE, true);
					break;
				case 'upload_file_exceeds_form_limit' :
					// 설정된 업로드 용량을 초과하였습니다.
					$line = 'allowed_maximum_upload_limit';
					$replace = get_file_size(POST_MAX_SIZE, true);
					break;
				case 'upload_invalid_filesize' :
					// 허용된 용량을 초과하였습니다.
					$line = 'allowed_maximum_upload_limit';
					$replace = get_file_size((int)$this->uploadConfig['max_size']*1024, true);
					break;
				case 'upload_invalid_filetype' :
					// 허용된 파일 확장자가 아닙니다.
					$line = 'allowed_upload_type';
					$replace = str_replace('|', ', ', $this->uploadConfig['allowed_types']);
					break;
			}

			$msg = ($this->_CI->lang->line($msg) === FALSE) ? $msg : $this->_CI->lang->line($msg);
			$append = $this->_CI->lang->nline($line, $replace, false);
			if($append) $msg .= "\n".$append;
		}

		return parent::set_error($msg, $log_level);
	}

    public function display_errors($open = '<p>', $close = '</p>')
    {
        if($this->_CI->input->is_ajax_request() || is_api_call()) $open = $close = '';
        return parent::display_errors($open, $close); // TODO: Change the autogenerated stub
    }
}
