<?php
defined('BASEPATH') or exit('No direct script access allowed');

require_once __DIR__.'/Common.php';

class Categories extends Common
{
    function __construct()
    {
        parent::__construct();

        $this->routeTitle = '카테고리';

        $this->validateModel('Model_Category', 'Model');

        $this->setProperties($this->Model);

        $this->defaultList = [
            'depth' => 1,
        ];

        $this->fileList = [
            'category_icon'
        ];

        // 관리 화면은 미사용 행도 보고 고친다. 공개 API·선택지 조회는 지금처럼 미사용 행을 뺀다
        if($this->flag === 'admin' && $this->input->get('_mode') !== 'option') $this->Model->useUseYnAsBase = false;
    }

    protected function beforeList($data): array
    {
        $data = parent::beforeList($data);
        // 기본은 정렬 순서, 목록 머리글로 정렬을 요청하면 그 순서 (MY_Builder_API::getRequestedListOrder)
        if(empty($data['orderBy'])) $data['orderBy'] = ['category_srt' => 'ASC'];
        return $data;
    }

    protected function beforePost($key = 0, $model = null): array
    {
        list($key, $data) = parent::beforePost($key);

        // 수정 화면은 바뀐 칸만 보내므로 use_yn 이 없을 수 있다 (수정의 순서는 executeModify 가 정한다)
        if(($data['use_yn'] ?? '') === 'N') $data['category_srt'] = 0;

        return [$key, $data];
    }

    protected function executeAdd($dto, $bool, $model = null): array
    {
        if(($dto['use_yn'] ?? '') === 'Y' && (int)($dto['category_srt'] ?? 0) === 0) {
            $dto['category_srt'] = $this->Model->getCnt(['where' => ['parent_id' => $dto['parent_id'], 'use_yn' => 'Y']]) + 1;
        }

        if($dto['category_srt'] === 0) {
            return parent::executeAdd($dto, $bool, $model); // TODO: Change the autogenerated stub
        }else{
            $dto = parent::executeAdd($dto, $bool, $model);
            $this->reorderList('category_srt', 'category_id', 'parent_id', [
                'where' => ['use_yn' => 'Y']
            ], $dto);
            return $dto;
        }
    }

    protected function executeModify($key, $dto, $bool, $model = null): array
    {
        // 인라인 수정(PATCH)은 본문에 식별자가 없을 수 있다. 대상은 checkIdentifierExist() 가 정한 값으로 찾는다
        $categoryId = $this->idData['category_id'] ?? ($dto['category_id'] ?? $key);
        $original = $this->Model->getData([], [
            'where' => ['category_id' => $categoryId],
        ]);

        $sameParent = ['parent_id' => $dto['parent_id'] ?? $original->parent_id];
        $useYn = $dto['use_yn'] ?? $original->use_yn;

        // 미사용 행은 순서 0, 다시 사용하면 같은 부모의 맨 뒤
        if($useYn === 'N') {
            $dto['category_srt'] = 0;
        }elseif($original->use_yn === 'N' && (int)($dto['category_srt'] ?? 0) === 0) {
            $dto['category_srt'] = $this->Model->getCnt(['where' => $sameParent + ['use_yn' => 'Y']]) + 1;
        }

        if(!array_key_exists('category_srt', $dto) || (int)$dto['category_srt'] === (int)$original->category_srt) {
            return parent::executeModify($key, $dto, $bool, $model); // TODO: Change the autogenerated stub
        }

        $dto = parent::executeModify($key, $dto, $bool, $model);

        if($useYn === 'N') {
            $this->reorderList('category_srt', 'category_id', 'parent_id', [
                'where' => $sameParent + ['use_yn' => 'Y'],
            ]);
        }else{
            // 부모별로 순서를 맞추도록 대상 행의 키를 함께 넘긴다 (수정 화면은 바뀐 칸만 보낸다)
            $this->reorderList('category_srt', 'category_id', 'parent_id', [
                'where' => ['use_yn' => 'Y']
            ], $sameParent + ['category_id' => (string)$categoryId] + $dto);
        }

        return $dto;
    }

    protected function executeRemove($key, $data, $bool): array
    {
        // 삭제 전에 대상 행에서 parent_id 를 읽는다 (DELETE 바디에는 parent_id 가 없음)
        $baseRow = $this->getDeleteBaseRow();

        $data = parent::executeRemove($key, $data, $bool);

        $this->reorderList('category_srt', 'category_id', 'parent_id', [
            'where' => ['parent_id' => $baseRow->parent_id, 'use_yn' => 'Y'],
        ]);

        return $data;
    }
}
