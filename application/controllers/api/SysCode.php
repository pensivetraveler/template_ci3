<?php
defined('BASEPATH') or exit('No direct script access allowed');

require_once __DIR__.'/Common.php';

class SysCode extends Common
{
    protected string $bigCd;
    protected string $smlCd;

    function __construct()
    {
        parent::__construct();

        $this->routeTitle = '시스템 코드';

        $this->validateModel('Model_Sys_Code', 'Model');

        $this->setProperties($this->Model);

        if($this->flag !== 'admin') show_404();
    }

    protected function beforeList($data): array
    {
        $data['whereNot'] = ['sml_cd' => '000'];
        $data = parent::beforeList($data);
        return $data;
    }

    protected function executeAdd($dto, $bool, $model = null): array
    {
        if($dto['sml_cd'] === '000') {
            return parent::executeAdd($dto, $bool);
        }else{
            $dto = parent::executeAdd($dto, $bool, $model);
            $this->reorderList('cd_srt', 'cmb_cd', 'big_cd', [
                'whereNot' => ['sml_cd' => '000']
            ], $dto);
            return $dto;
        }
    }

    protected function executeModify($key, $dto, $bool, $model = null): array
    {
        // 수정 대상은 URL로 확인한 식별자($this->idData) 기준. 부분 PATCH(cd_name만 등)에서는 dto에 sml_cd·cmb_cd가 없다
        $original = $this->Model->getData([], [
            'where' => count($this->idData) ? $this->idData : ['cmb_cd' => $dto['cmb_cd'] ?? null],
        ]);
        $smlCd = $dto['sml_cd'] ?? ($original->sml_cd ?? null);

        if(!$original || $smlCd === '000') {
            return parent::executeModify($key, $dto, $bool); // TODO: Change the autogenerated stub
        }else{
            if(!array_key_exists('cd_srt', $dto) || (int)$dto['cd_srt'] === (int)$original->cd_srt) {
                return parent::executeModify($key, $dto, $bool, $model); // TODO: Change the autogenerated stub
            }else{
                $dto = parent::executeModify($key, $dto, $bool, $model);
                // 정렬 기준(같은 big_cd 그룹, 자기 자신 제외)이 빠지지 않도록 원래 행의 키를 채움
                $this->reorderList('cd_srt', 'cmb_cd', 'big_cd', [
                    'whereNot' => ['sml_cd' => '000']
                ], array_merge(['cmb_cd' => $original->cmb_cd, 'big_cd' => $original->big_cd], $dto));
                return $dto;
            }
        }
    }

    protected function beforeRemove($key = 0, $data = []): array
    {
        // 삭제 대상은 checkIdentifierExist() 가 정한 idData(cmb_cd) 기준. bigCd 는 일반 코드 삭제 후 재정렬에도 쓰므로 항상 채운다
        $cmbCd = (string)($this->idData['cmb_cd'] ?? $key);
        $this->smlCd = substr($cmbCd, 3);
        $this->bigCd = substr($cmbCd, 0, 3);

        if($this->smlCd === '000') {
            if ($this->Model->getCntWhere(['big_cd' => $this->bigCd,]) > 1) {
                $this->response(['code' => BAD_REQUEST, 'msg' => 'You Should Delete Codes In The Category']);
            }
        }

        return parent::beforeRemove($key, $data);
    }

    protected function executeRemove($key, $data, $bool): array
    {
        $data = parent::executeRemove($key, $data, $bool);

        if($this->smlCd !== '000') {
            $this->reorderList('cd_srt', 'cmb_cd', 'big_cd', [
                'where' => ['big_cd' => $this->bigCd],
                'whereNot' => ['sml_cd' => '000']
            ]);
        }

        return $data;
    }
}
