<?php
defined('BASEPATH') or exit('No direct script access allowed');

require_once __DIR__.'/Common.php';

class ArticleRead extends Common
{
	function __construct()
	{
		parent::__construct();

		$this->load->model('Model_Article_Read', 'Model');
		$this->load->model('Model_Article');
		$this->load->model('Model_User');

		$this->setProperties($this->Model);
	}

	protected function beforePut($key = 0, $model = null): array
	{
		// parent 는 [$key, $data] 를 돌려준다 (예전에는 배열 전체를 dto 로 써서 where 에 0/1 키가 들어갔다)
		list($key, $dto) = parent::beforePut($key, $model); // TODO: Change the autogenerated stub

		if(empty($dto['article_id'])) $this->response(['code' => EMPTY_REQUIRED_DATA]);

		$where = [
			'article_id' => $dto['article_id'],
			'user_id' => $this->session->userdata('user_id'),
		];
		$dto = array_merge($dto, $where, ['read_dt' => date('Y-m-d H:i:s')]);

		// 읽음 기록은 (article_id, user_id) 로 찾는다. read_dt 까지 조건에 넣으면 항상 없음
		$readData = $this->Model->getData([], [
			'where' => $where,
		]);
		if($readData) {
			if(time() < strtotime((string)$readData->read_dt) + 60*60) {
				$this->response([
					'code' => DATA_PROCESSED,
				]);
			}
			// 기존 행의 read_dt 를 갱신하도록 수정 대상으로 지정 (없으면 add 로 가서 409)
			$this->idData = $where;
		}

		$this->Model_Article->modNumb('view_count', 1, [
			'article_id' => $dto['article_id'],
		]);

		return [$key, $dto];
	}

}
