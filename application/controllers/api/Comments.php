<?php
defined('BASEPATH') or exit('No direct script access allowed');

require_once __DIR__.'/Common.php';

class Comments extends Common
{
	function __construct()
	{
		parent::__construct();

        $this->routeTitle = '댓글';

		$this->load->model('Model_Comment', 'Model');
		$this->load->model('Model_Message');
		$this->load->model('Model_Article');

		$this->setProperties($this->Model);

		$this->defaultList = [
			'del_yn' => 'N',
		];
	}

    protected function beforeList($data): array
    {
        $data['where']['depth'] = 0;

        return parent::beforeList($data); // TODO: Change the autogenerated stub
    }

    protected function transformList($list): array
    {
        // Common::transformView() 가 created_id 를 로그인 id 로 바꾸므로 원래 user_id 를 먼저 보관
        $createdIds = [];
        foreach ($list as $k => $item) $createdIds[$k] = $item->created_id ?? null;

        $list = parent::transformList($list); // TODO: Change the autogenerated stub

        // getListWhere 에 컬럼 1개를 주면 값 배열(user_id 목록)을 돌려준다
        $adminList = $this->Model_User->getListWhere(['user_id'], [
            'user_cd' => 'USR001'
        ]);

        // 답글을 한 번에 조회 (댓글마다 조회하던 N+1 제거)
        $commentIds = array_values(array_filter(array_column($list, 'comment_id')));
        $replyMap = [];
        if(count($commentIds)) {
            $replyList = $this->Model->getList([], [
                'where' => [
                    'parent_id' => $commentIds,
                    'depth' => 1,
                ],
                'orderBy' => ['created_dt' => 'desc'],
            ]);
            foreach ($replyList as $reply) $replyMap[$reply->parent_id][] = $reply;
        }

        // 작성자도 한 번에 조회
        $userIds = array_merge(array_values($createdIds), array_column($replyList ?? [], 'created_id'));
        $userIds = array_values(array_unique(array_filter($userIds)));
        $userMap = [];
        if(count($userIds)) {
            foreach ($this->Model_User->getListWhere(['user_id', 'name', 'id'], ['user_id' => $userIds]) as $user) {
                $userMap[$user->user_id] = (object)['name' => $user->name, 'id' => $user->id];
            }
        }

        $userId = (int)$this->session->userdata('user_id');
        foreach ($list as $k => $item) {
            $createdId = $createdIds[$k] ?? null;
            $item->creater = $userMap[(string)$createdId] ?? null;
            $item->is_admin = in_array($createdId, $adminList);
            $item->mine_yn = $userId === (int)$createdId;

            $replies = $replyMap[$item->comment_id] ?? [];
            foreach ($replies as $reply) {
                $reply->mine_yn = $userId === (int)$reply->created_id;
                $reply->is_admin = in_array($reply->created_id, $adminList);
                $reply->creater = $userMap[(string)$reply->created_id] ?? null;
            }
            $item->reply_list = $replies;
        }

        return $list;
    }

	// 등록 후 hook 이름은 afterAdd (예전 afterAddData 는 호출되지 않아 알림이 만들어지지 않았다)
	protected function afterAdd($dto)
	{
		$this->addCommentMessage($dto);

		parent::afterAdd($dto);
	}

	protected function addCommentMessage($dto): void
	{
		if(empty($dto['article_id']) || empty($dto['comment_id'])) return;

		$article = $this->Model_Article->getData([], [
			'where' => ['article_id' => $dto['article_id'],]
		]);
		if(!$article || (int)$article->board_id !== 3) return;

		if(empty($dto['parent_id'])) {
			// 댓글
			if((int)$article->created_id !== (int)$this->session->userdata('user_id')) {
				$this->Model_Message->addData([
					'user_id' => $article->created_id,
					'article_id' => $dto['article_id'],
					'comment_id' => $dto['comment_id'],
					'content' => '내 게시글에 새 댓글이 달렸어요.',
					'read_yn' => 'N',
				]);
			}
		}else{
			$parentComment = $this->Model->getDataWhere([], [
				'article_id' => $dto['article_id'],
				'comment_id' => $dto['parent_id'],
			]);

			// 답글
			if($parentComment && (int)$parentComment->created_id !== (int)$this->session->userdata('user_id')) {
				// 답글 대상 댓글 작성자와 답글 작성자가 서로 다른 경우
				$this->Model_Message->addData([
					'user_id' => $parentComment->created_id,
					'article_id' => $dto['article_id'],
					'comment_id' => $dto['comment_id'],
					'content' => '내 댓글에 새 답글이 달렷어요.',
					'read_yn' => 'N',
				]);
			}
		}
	}
}
